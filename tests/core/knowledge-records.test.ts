import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import { afterEach, describe, expect, it, vi } from 'vitest'
import { ProjectStore } from '../../src/core/project-store'
import { SourceCatalogRepository } from '../../src/core/source-catalog'
import { KnowledgeRecordsRepository } from '../../src/core/knowledge-records'
import { ProjectDirectoryRepository } from '../../src/core/project-directory'
import { WorkItemRepository } from '../../src/core/work-items'
import { FrozenClock } from '../../src/core/clock'
import { inspectKnowledgeReference, referenceKey } from '../../src/core/knowledge-references'

const stores: ProjectStore[] = []
const roots: string[] = []
afterEach(async () => { vi.restoreAllMocks(); stores.splice(0).forEach((store) => store.close()); await Promise.all(roots.splice(0).map((root) => rm(root, { recursive: true, force: true }))) })
async function fixture() {
  const root = await mkdtemp(path.join(os.tmpdir(), 'workstack-records-'))
  roots.push(root)
  const store = await ProjectStore.initialize({ rootPath: root, name: 'Typed knowledge' })
  stores.push(store)
  const clock = new FrozenClock(new Date('2026-09-09T00:00:00.000Z'))
  const catalog = new SourceCatalogRepository(store, { clock })
  const source = catalog.registerSource({ kind: 'manual', title: 'Architecture', canonicalUri: 'manual://architecture' })
  catalog.publishRevision({ sourceId: source.id, original: '# Durable queue\nSQLite retains pending jobs across restarts.\n' })
  return { root, store, clock, catalog, source, citation: catalog.search('SQLite')[0].citation, records: new KnowledgeRecordsRepository(store, { clock }) }
}

describe('typed knowledge records', () => {
  it('distinguishes unresolved decisions from accepted guidance and preserves superseded rationale and evidence', async () => {
    const { records, citation } = await fixture()
    const original = records.create({ kind: 'decision', title: 'Queue storage', markdown: 'Use SQLite for durable jobs.', rationale: 'Keep transactional ownership.', references: [{ kind: 'source', citation }] })
    expect(original).toMatchObject({ status: 'proposed', current: false, readiness: 'needs_review' })
    expect(records.checks()).toEqual(expect.arrayContaining([expect.objectContaining({ code: 'unresolved_decision', recordId: original.id })]))
    const accepted = records.update(original.id, { expectedVersion: original.version, status: 'accepted' }, 'owner', 'Design accepted.')
    expect(accepted).toMatchObject({ current: true, readiness: 'ready' })
    expect(records.checks().some((finding) => finding.code === 'unresolved_decision')).toBe(false)
    const replacement = records.create({ kind: 'decision', title: 'Queue storage v2', status: 'accepted', markdown: 'Use SQLite with fenced leases.', rationale: 'Prevent old owners from publishing.', references: [{ kind: 'source', citation }] })
    const history = records.supersede(original.id, replacement.id, 'owner', 'The ownership model has changed.')
    expect(history).toMatchObject({ status: 'superseded', supersededBy: replacement.id, rationale: original.rationale, current: false, readiness: 'historical' })
    expect(records.search('SQLite').map((record) => record.id)).toEqual([replacement.id])
    expect(records.search('SQLite', { includeHistorical: true }).map((record) => record.id)).toContain(original.id)
    expect(records.history(original.id).map((record) => record.snapshot.status)).toEqual(['superseded', 'accepted', 'proposed'])
    expect(records.readMarkdown(original.id)).toContain(`Superseded by: ${replacement.id}`)
    expect(() => records.update(original.id, { expectedVersion: history.version, markdown: 'Rewrite history.' })).toThrow('original rationale')
    expect(() => records.supersede(replacement.id, original.id, 'owner', 'Reverse cycle.')).toThrow('current record')
  })

  it('rejects cross-type or self supersession and invalid lifecycle states', async () => {
    const { records } = await fixture()
    expect(() => records.create({ kind: 'requirement', status: 'accepted', title: 'Invalid', markdown: 'Invalid.' })).toThrow('invalid for a requirement')
    expect(() => records.create({ kind: 'decision', status: 'superseded', title: 'Invalid', markdown: 'Invalid.' })).toThrow('Use supersede')
    const decision = records.create({ kind: 'decision', status: 'accepted', title: 'Decision', markdown: 'Context.' })
    const risk = records.create({ kind: 'risk', title: 'Risk', markdown: 'Known operational risk.' })
    expect(() => records.supersede(decision.id, risk.id, 'owner', 'Wrong type.')).toThrow('same kind')
    expect(() => records.supersede(decision.id, decision.id, 'owner', 'Self reference.')).toThrow('different current record')
    expect(() => records.update(risk.id, { expectedVersion: 5, status: 'closed' })).toThrow('changed')
  })

  it('supports explicit requirements and risks with work item, component, file and source references', async () => {
    const { root, store, records, citation } = await fixture()
    await writeFile(path.join(root, 'queue.ts'), 'export class Queue {}\n')
    const component = new ProjectDirectoryRepository(store).create({ kind: 'component', displayName: 'Queue', definition: 'Durable worker queue.' })
    const task = new WorkItemRepository(store).create({ type: 'feature', title: 'Recover jobs' })
    const requirement = records.create({ kind: 'requirement', status: 'active', title: 'Restart recovery', markdown: 'Resume unexpired jobs after restart.', references: [{ kind: 'source', citation }, { kind: 'file', path: 'queue.ts' }, { kind: 'work_item', id: task.id }, { kind: 'entity', id: component.id }] })
    const risk = records.create({ kind: 'risk', title: 'Late owner', markdown: 'An expired owner may complete.', references: [{ kind: 'record', id: requirement.id }, { kind: 'source', citation }] })
    expect(requirement.readiness).toBe('ready')
    expect(risk).toMatchObject({ status: 'open', current: true, readiness: 'ready' })
    expect(records.update(risk.id, { expectedVersion: risk.version, status: 'mitigated' }).current).toBe(true)
    expect(records.update(requirement.id, { expectedVersion: requirement.version, status: 'fulfilled' }).readiness).toBe('historical')
  })

  it('returns stable actionable findings, tracks evidence freshness, and removes findings after repair', async () => {
    const { records, catalog, source, citation } = await fixture()
    let record = records.create({ kind: 'decision', title: 'Queue', status: 'accepted', markdown: 'Use a queue.', references: [{ kind: 'file', path: 'missing.ts' }, { kind: 'work_item', id: 'missing' }] })
    const before = records.checks()
    expect(before.filter((finding) => finding.code === 'broken_reference')).toHaveLength(2)
    expect(records.checks()).toEqual(before)
    record = records.update(record.id, { expectedVersion: record.version, references: [] })
    expect(records.checks()).toEqual([expect.objectContaining({ code: 'missing_evidence', recordId: record.id, action: expect.any(String), locator: record.locator })])
    record = records.update(record.id, { expectedVersion: record.version, references: [{ kind: 'source', citation }] })
    expect(records.checks()).toEqual([])
    catalog.publishRevision({ sourceId: source.id, original: 'New queue evidence.' })
    expect(records.get(record.id).readiness).toBe('needs_review')
    expect(records.checks()).toEqual([expect.objectContaining({ code: 'stale_evidence', recordId: record.id })])
    expect(catalog.listInvalidations()).toEqual(expect.arrayContaining([expect.objectContaining({ artifactKind: 'knowledge_record', artifactId: record.id })]))
    const fresh = catalog.search('queue')[0].citation
    records.update(record.id, { expectedVersion: record.version, references: [{ kind: 'source', citation: fresh }] })
    expect(records.checks()).toEqual([])
  })

  it('keeps review history separate from formatting changes and allows clearing optional metadata', async () => {
    const { records, clock, citation } = await fixture()
    let record = records.create({ kind: 'decision', title: 'Queue', status: 'accepted', markdown: 'Use **SQLite**.', references: [{ kind: 'source', citation }], confidence: 0.8, reviewDueAt: '2026-09-08T00:00:00.000Z' })
    const due = records.checks().find((finding) => finding.code === 'review_due')
    expect(due?.reason).toContain('Age alone')
    const review = records.review(record.id, { actor: 'owner', note: 'Checked against current architecture evidence.', outcome: 'confirmed', reviewDueAt: '2026-10-09T00:00:00.000Z' })
    clock.advance(3_600_000)
    record = records.update(record.id, { expectedVersion: record.version, markdown: 'Use __SQLite__.' }, 'editor', 'Only emphasis formatting changed.')
    expect(record.lastReviewedAt).toBe(review.reviewedAt)
    expect(record.updatedAt).not.toBe(record.lastReviewedAt)
    expect(records.reviews(record.id)).toEqual([review])
    expect(() => records.review(record.id, { actor: 'owner', note: 'Stale view confirmation.', outcome: 'confirmed', expectedVersion: 1 })).toThrow('Reload its current content')
    expect(records.checks()).toEqual([])
    records.review(record.id, { actor: 'owner', note: 'Please document operational constraints.', outcome: 'needs_changes' })
    expect(records.checks()).toEqual([expect.objectContaining({ code: 'review_requested' })])
    record = records.update(record.id, { expectedVersion: record.version, confidence: null, reviewDueAt: null })
    expect(record.confidence).toBeUndefined()
    expect(record.reviewDueAt).toBeUndefined()
    expect(record.lastReviewedAt).toBe(review.reviewedAt)
    records.review(record.id, { actor: 'owner', note: 'Reviewed operational constraints.', outcome: 'confirmed' })
    expect(records.checks()).toEqual([])
  })

  it('reports malformed legacy metadata and corrupt supersession cycles reproducibly', async () => {
    const { store, records } = await fixture()
    const first = records.create({ kind: 'decision', status: 'accepted', title: 'First', markdown: 'First rationale.' })
    const second = records.create({ kind: 'decision', status: 'accepted', title: 'Second', markdown: 'Second rationale.' })
    store.database.prepare("UPDATE knowledge_records SET status='superseded',superseded_by=? WHERE id=?").run(second.id, first.id)
    store.database.prepare("UPDATE knowledge_records SET status='superseded',superseded_by=? WHERE id=?").run(first.id, second.id)
    expect(records.checks().filter((finding) => finding.code === 'supersession_cycle')).toHaveLength(2)
    store.database.prepare("UPDATE knowledge_records SET references_json='not-json' WHERE id=?").run(first.id)
    expect(records.checks()).toEqual(expect.arrayContaining([expect.objectContaining({ code: 'invalid_metadata', recordId: first.id })]))
  })

  it('isolates records and references by project and redacts sensitive text before context use', async () => {
    const first = await fixture()
    const second = await fixture()
    const record = first.records.create({ kind: 'decision', title: 'Use ghp_ABCDEFGHIJKLMNOPQRSTUVWXYZ1234', status: 'accepted', markdown: 'api_key=privatevalue', references: [{ kind: 'source', citation: first.citation }] })
    expect(record.title).toContain('[REDACTED CREDENTIAL]')
    expect(record.markdown).not.toContain('privatevalue')
    expect(() => second.records.get(record.id)).toThrow('does not exist in this project')
    const broken = second.records.create({ kind: 'decision', title: 'Foreign evidence', status: 'accepted', markdown: 'Keep references project-local.', references: [{ kind: 'source', citation: first.citation }] })
    expect(second.records.checks()).toEqual([expect.objectContaining({ code: 'broken_reference', recordId: broken.id })])
  })
  it('follows wiki evidence from legacy content through tracked publication and loss of availability', async () => {
    const { store, catalog, records, clock } = await fixture()
    const reference = { kind: 'wiki' as const, slug: 'queue-policy' }
    expect(inspectKnowledgeReference(store, reference, clock)?.code).toBe('broken_reference')
    await writeFile(path.join(store.paths.wikiPath, 'queue-policy.md'), '# Queue policy\nKeep ownership durable.')
    expect(inspectKnowledgeReference(store, reference, clock)).toBeUndefined()
    const record = records.create({ kind: 'requirement', title: 'Queue policy', status: 'active', markdown: 'Follow the published policy.', references: [reference] })
    expect(records.readMarkdown(record.id)).toContain('wiki:queue-policy')
    expect(records.checks()).toEqual([])
    const source = catalog.registerSource({ id: 'wiki:queue-policy', kind: 'wiki', title: 'Queue policy', canonicalUri: 'wiki://queue-policy' })
    expect(inspectKnowledgeReference(store, reference, clock)?.code).toBe('broken_reference')
    catalog.publishRevision({ sourceId: source.id, original: '# Queue policy\nKeep ownership durable.' })
    expect(inspectKnowledgeReference(store, reference, clock)).toBeUndefined()
    catalog.recordFreshness(source.id, { unavailable: true, reason: 'Publication is temporarily offline.' })
    expect(inspectKnowledgeReference(store, reference, clock)?.code).toBe('stale_evidence')
    catalog.recordFreshness(source.id, { unavailable: true, deleted: true, reason: 'Publication removed.' })
    expect(inspectKnowledgeReference(store, reference, clock)?.code).toBe('broken_reference')
  })
  it('keeps linked record and component lifecycle changes visible to knowledge checks', async () => {
    const { store, records, citation, clock } = await fixture()
    expect(inspectKnowledgeReference(store, { kind: 'record', id: 'missing' }, clock)?.code).toBe('broken_reference')
    expect(inspectKnowledgeReference(store, { kind: 'entity', id: 'missing' }, clock)?.code).toBe('broken_reference')
    const original = records.create({ kind: 'decision', title: 'Old policy', status: 'accepted', markdown: 'Old guidance.', references: [{ kind: 'source', citation }] })
    const replacement = records.create({ kind: 'decision', title: 'New policy', status: 'accepted', markdown: 'New guidance.', references: [{ kind: 'source', citation }] })
    records.supersede(original.id, replacement.id, 'owner', 'Updated policy.')
    expect(inspectKnowledgeReference(store, { kind: 'record', id: original.id }, clock)?.code).toBe('stale_evidence')
    const directory = new ProjectDirectoryRepository(store, { clock })
    const entity = directory.create({ kind: 'term', displayName: 'Legacy queue', definition: 'The retired design.' })
    directory.retire(entity.id, entity.version, 'owner', 'The component was removed.')
    expect(inspectKnowledgeReference(store, { kind: 'entity', id: entity.id }, clock)?.code).toBe('stale_evidence')
    expect(referenceKey({ kind: 'file', path: 'queue.ts' })).toBe('file:queue.ts')
    expect(records.list({ kind: 'decision', includeHistorical: true, limit: 1 })).toHaveLength(1)
    expect(records.list({ kind: 'risk' })).toEqual([])
    expect(records.search('!?')).toEqual([])
  })
  it('rejects incomplete review attribution and leaves records unchanged on invalid review input', async () => {
    const { records, citation } = await fixture()
    const record = records.create({ kind: 'decision', title: 'Policy', status: 'accepted', markdown: 'Approved guidance.', references: [{ kind: 'source', citation }] })
    expect(() => records.review(record.id, { actor: ' ', note: 'Reviewed.', outcome: 'confirmed' })).toThrow('actor')
    expect(() => records.review(record.id, { actor: 'owner', note: ' ', outcome: 'confirmed' })).toThrow('reason')
    expect(() => records.review(record.id, { actor: 'owner', note: 'Reviewed.', outcome: 'confirmed', reviewDueAt: 'next week' })).toThrow('due date')
    expect(records.reviews(record.id)).toEqual([])
    records.review(record.id, { actor: 'owner', note: 'Need a fuller rationale.', outcome: 'needs_changes', reviewDueAt: '2026-10-01T00:00:00.000Z', expectedVersion: record.version })
    expect(records.get(record.id).reviewDueAt).toBe('2026-10-01T00:00:00.000Z')
    records.review(record.id, { actor: 'owner', note: 'Evidence confirmed.', outcome: 'confirmed', expectedVersion: record.version })
    expect(records.readMarkdown(record.id)).toContain('Last reviewed:')
    expect(records.history(record.id)).toHaveLength(1)
  })
  it('reports inconsistent imported metadata and refuses supersession through a malformed chain', async () => {
    const { store, records, citation } = await fixture()
    const first = records.create({ kind: 'decision', title: 'First imported decision', status: 'accepted', markdown: 'First guidance.', references: [{ kind: 'source', citation }] })
    const second = records.create({ kind: 'decision', title: 'Second imported decision', status: 'accepted', markdown: 'Second guidance.', references: [{ kind: 'source', citation }] })
    store.database.prepare('UPDATE knowledge_records SET superseded_by=? WHERE id=?').run(first.id, second.id)
    expect(records.checks()).toEqual(expect.arrayContaining([expect.objectContaining({ recordId: second.id, code: 'invalid_metadata' })]))
    expect(() => records.supersede(first.id, second.id, 'owner', 'Reject the imported cycle.')).toThrow('cycle')
    expect(records.get(first.id).status).toBe('accepted')
    const risk = records.create({ kind: 'risk', title: 'Imported risk', markdown: 'Risk guidance.' })
    store.database.prepare("UPDATE knowledge_records SET status='superseded',superseded_by=? WHERE id=?").run(risk.id, first.id)
    expect(records.checks()).toEqual(expect.arrayContaining([expect.objectContaining({ recordId: first.id, code: 'broken_reference', reason: expect.stringContaining('different type') })]))
    expect(records.list()).toEqual(expect.not.arrayContaining([expect.objectContaining({ id: first.id })]))
    expect(records.readMarkdown(risk.id)).toContain('Not recorded.')
  })
  it('reports unsupported file evidence and unexpected reader failures as actionable findings', async () => {
    const { root, store, records, citation, clock } = await fixture()
    expect(inspectKnowledgeReference(store, { kind: 'file', path: path.resolve(root, 'absolute.ts') }, clock)).toMatchObject({ code: 'broken_reference', reason: expect.stringContaining('outside permitted') })
    await mkdir(path.join(root, 'folder'))
    expect(inspectKnowledgeReference(store, { kind: 'file', path: 'folder' }, clock)).toMatchObject({ code: 'broken_reference', reason: expect.stringContaining('project file') })
    await mkdir(path.join(store.paths.wikiPath, 'folder.md'))
    expect(inspectKnowledgeReference(store, { kind: 'wiki', slug: 'folder' }, clock)).toMatchObject({ code: 'broken_reference', reason: expect.stringContaining('does not exist') })
    vi.spyOn(SourceCatalogRepository.prototype, 'readCitation').mockImplementationOnce(() => { throw 'Source reader unavailable.' })
    expect(inspectKnowledgeReference(store, { kind: 'source', citation }, clock)).toEqual({ code: 'broken_reference', reason: 'The reference could not be resolved.' })
    const record = records.create({ kind: 'decision', title: 'Metadata failure', markdown: 'Pending guidance.' })
    vi.spyOn(JSON, 'parse').mockImplementationOnce(() => { throw 'Metadata reader unavailable.' })
    expect(records.checks()).toEqual([expect.objectContaining({ recordId: record.id, code: 'invalid_metadata', reason: 'Invalid record metadata.' })])
  })
})
